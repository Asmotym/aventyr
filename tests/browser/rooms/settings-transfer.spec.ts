import { test, expect } from '@playwright/test';
import { setup, navigate } from '../support/rooms.fixture';
import { emptySettingsPackage } from '../../../shared/rooms/settings-transfer';

for (const mobile of [false, true]) test(`global settings transfer requires selection, mode and confirmation (${mobile ? 'mobile' : 'desktop'})`, async ({ page }) => {
    if (mobile) await page.setViewportSize({ width: 390, height: 844 });
    await setup(page);
    const data = emptySettingsPackage(); data.sections.room = { values: { name: 'Imported room' }, lists: {} };
    data.sections.rollAwards = { values: { enabled: true }, lists: { awards: [{ name: 'Hero', diceResults: [20], diceNotations: ['d20'] }, { name: 'Lucky', diceResults: [1], diceNotations: ['d20'] }] } };
    const writes: Array<{ action: string; payload: { package?: typeof data; mode?: string; token?: string } }> = [];
    await page.route('**/api/rooms/settings-transfer', async route => {
        const body = route.request().postDataJSON(); writes.push(body);
        if (body.action === 'exportSettings') return route.fulfill({ json: { success: true, data: { settingsPackage: data } } });
        if (body.action === 'previewSettingsImport') return route.fulfill({ json: { success: true, data: { settingsPreview: { token: 'confirmed', changes: [{ section: 'rollAwards', added: [{ name: 'Hero' }], removed: [], archived: [], values: {} }] } } } });
        return route.fulfill({ json: { success: true, data: { settingsImported: true, roomId: 'room' } } });
    });
    await page.getByRole('button', { name: 'Room settings', exact: true }).click();
    const nav = page.locator('.room-settings-dialog__navigation');
    await expect(nav.locator('.v-list-item').last()).toContainText('Import/Export');
    await navigate(page, 'Import/Export');
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Import', exact: true }).click();
    await page.locator('.room-settings-transfer input[type=file]').setInputFiles({ name: 'settings.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) });
    const popup = page.getByRole('dialog', { name: 'Import', exact: true });
    await expect(popup.getByRole('button', { name: 'Import', exact: true })).toBeDisabled();
    await popup.getByRole('checkbox', { name: 'Lucky', exact: true }).uncheck();
    await popup.getByRole('radio', { name: 'Add', exact: true }).check();
    await popup.getByRole('button', { name: 'Import', exact: true }).click();
    const confirm = page.getByRole('dialog', { name: 'Review import', exact: true });
    await expect(confirm).toBeVisible();
    expect(writes.filter(body => body.action === 'importSettings')).toHaveLength(0);
    expect(writes.find(body => body.action === 'previewSettingsImport')!.payload.package!.sections.rollAwards!.lists.awards).toHaveLength(1);
    await confirm.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(popup).toBeVisible();
    await popup.getByRole('button', { name: 'Import', exact: true }).click();
    await confirm.getByRole('button', { name: 'Confirm Import', exact: true }).click();
    await expect(popup).not.toBeVisible();
    expect(writes.find(body => body.action === 'importSettings')!.payload.token).toBe('confirmed');
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Export', exact: true }).click();
    const exporting = page.getByRole('dialog', { name: 'Export', exact: true });
    await expect(exporting.getByRole('checkbox', { name: 'Hero', exact: true })).toBeChecked();
    const downloadEvent = page.waitForEvent('download'); await exporting.getByRole('button', { name: 'Export to File', exact: true }).click();
    expect((await downloadEvent).suggestedFilename()).toMatch(/settings\.json$/);
    await page.keyboard.press('Escape');
    await expect(exporting).not.toBeVisible();
});

test('invalid file is recoverable and Cancel clears only the import recap', async ({ page }) => {
    await setup(page); await page.getByRole('button', { name: 'Room settings', exact: true }).click(); await navigate(page, 'Import/Export');
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Import', exact: true }).click();
    const input = page.locator('.room-settings-transfer input[type=file]'), popup = page.getByRole('dialog', { name: 'Import', exact: true });
    await input.setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{oops') });
    await expect(page.getByText('Invalid JSON', { exact: true })).toBeVisible();
    await input.setInputFiles({ name: 'awards.json', mimeType: 'application/json', buffer: Buffer.from('[{"name":"Hero","diceResults":[20]}]') });
    await expect(popup.getByRole('checkbox', { name: 'Hero', exact: true })).toBeVisible();
    await popup.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(popup).toBeVisible(); await expect(popup.getByRole('checkbox')).toHaveCount(0);
    await expect(popup.getByRole('button', { name: 'Import From File', exact: true })).toBeVisible();
});

test('clipboard fallback, replacement preview errors and clipboard export preserve selection', async ({ page }) => {
    await setup(page);
    const data = emptySettingsPackage(); data.sections.bag = { values: { enabled: false }, lists: {} };
    let rejectPreview = true;
    await page.route('**/api/rooms/settings-transfer', async route => {
        const body = route.request().postDataJSON();
        if (body.action === 'exportSettings') return route.fulfill({ json: { success: true, data: { settingsPackage: data } } });
        if (rejectPreview) return route.fulfill({ status: 403, json: { success: false, error: 'Missing room permission' } });
        return route.fulfill({ json: { success: true, data: { settingsPreview: { token: 'new', changes: [{ section: 'bag', added: [], removed: [], archived: [], values: { enabled: { before: true, after: false } } }] } } } });
    });
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: async () => { throw new Error('Clipboard denied'); }, writeText: async (text: string) => { (window as unknown as { copied: string }).copied = text; } } }));
    await page.getByRole('button', { name: 'Room settings', exact: true }).click(); await navigate(page, 'Import/Export');
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Import', exact: true }).click();
    const popup = page.getByRole('dialog', { name: 'Import', exact: true });
    await popup.getByRole('button', { name: 'Import From Clipboard', exact: true }).click();
    await expect(popup.getByText('Clipboard access is unavailable. Paste the JSON below.')).toBeVisible();
    await popup.getByRole('textbox', { name: /^JSON/ }).fill(JSON.stringify(data));
    await popup.getByRole('button', { name: 'Review', exact: true }).click();
    await popup.getByRole('radio', { name: 'Replace', exact: true }).check();
    await popup.getByRole('button', { name: 'Import', exact: true }).click();
    await expect(page.getByText('Missing room permission', { exact: true })).toBeVisible();
    await expect(popup.getByRole('checkbox', { name: 'Enabled: No', exact: true })).toBeChecked();
    rejectPreview = false;
    await popup.getByRole('button', { name: 'Import', exact: true }).click();
    const confirmation = page.getByRole('dialog', { name: 'Review import', exact: true });
    await expect(confirmation).toBeVisible(); await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(confirmation).not.toBeVisible();
    await popup.getByRole('button', { name: 'Close', exact: true }).click(); await expect(popup).not.toBeVisible();
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Export', exact: true }).click();
    await page.getByRole('dialog', { name: 'Export', exact: true }).getByRole('button', { name: 'Export to Clipboard', exact: true }).click();
    const copied = await page.evaluate(() => (window as unknown as { copied: string }).copied);
    expect(JSON.parse(copied).sections.bag.values.enabled).toBe(false);
});

for (const theme of ['light', 'dark']) for (const mobile of [false, true]) test(`transfer layout fits ${theme} ${mobile ? 'mobile' : 'desktop'}`, async ({ page }, info) => {
    await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
    await setup(page, theme);
    const data = emptySettingsPackage();
    data.sections.room = { values: { name: 'Campaign settings', sessionInactivityMinutes: 240 }, lists: {} };
    data.sections.rollAwards = { values: { enabled: true }, lists: { awards: [{ name: 'Hero', description: 'Award for the highest roll', diceResults: [20], diceNotations: ['d20'] }] } };
    await page.route('**/api/rooms/settings-transfer', route => route.fulfill({ json: { success: true, data: { settingsPackage: data } } }));
    await page.getByRole('button', { name: 'Room settings', exact: true }).click(); await navigate(page, 'Import/Export');
    expect(await page.locator('.room-slide-panel:visible').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('transfer-panel.png'), animations: 'disabled' });
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Export', exact: true }).click();
    const popup = page.getByRole('dialog', { name: 'Export', exact: true });
    await expect(popup.getByRole('checkbox', { name: 'Hero', exact: true })).toBeVisible();
    const card = await popup.locator('.v-card').boundingBox();
    expect(card!.x).toBeGreaterThanOrEqual(0); expect(card!.x + card!.width).toBeLessThanOrEqual(mobile ? 390 : 1440);
    expect(await popup.locator('.v-card').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('transfer-export.png'), animations: 'disabled' });
    await popup.getByRole('button', { name: 'Close', exact: true }).click();
    await expect(popup).not.toBeVisible();
    await page.locator('.room-settings-transfer').getByRole('button', { name: 'Import', exact: true }).click();
    await page.locator('.room-settings-transfer input[type=file]').setInputFiles({ name: 'settings.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) });
    const importing = page.getByRole('dialog', { name: 'Import', exact: true });
    await importing.getByRole('radio', { name: 'Replace', exact: true }).check();
    expect(await importing.locator('.v-card').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('transfer-import.png'), animations: 'disabled' });
});
