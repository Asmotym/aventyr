import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { markdownToDocument } from '../core/articles/render';
import type { ArticleTranslations } from '../core/articles/document';

test('Articles MySQL: translations, publication, migration, permissions and image lifecycle', { skip: process.env.ARTICLES_INTEGRATION !== '1' }, async () => {
    const { config } = await import('dotenv'); config();
    const mysql = await import('mysql2/promise');
    const database = `rolz_articles_test_${randomUUID().replaceAll('-', '')}`;
    const admin = await mysql.createConnection({ host: '127.0.0.1', port: Number(process.env.MYSQL_PORT ?? 3306), user: 'root', password: process.env.MYSQL_ROOT_PASSWORD ?? 'root' });
    let db: typeof import('../core/database/client') | undefined;
    try {
        await admin.query(`CREATE DATABASE \`${database}\``);
        const url = new URL(`mysql://root@127.0.0.1:${process.env.MYSQL_PORT ?? 3306}/${database}`); url.password = process.env.MYSQL_ROOT_PASSWORD ?? 'root';
        process.env.DATABASE_URL = url.toString(); process.env.DATABASE_SSL = 'false';
        db = await import('../core/database/client');
        const { ensureDatabaseSetup } = await import('../core/database/schema');
        await ensureDatabaseSetup(); await ensureDatabaseSetup();
        for (const [id, role] of [['owner','owner'],['admin','admin'],['reader','user']]) await db.execute("INSERT INTO users (discord_user_id, username, avatar, role) VALUES (?, ?, '', ?)", [id,id,role]);
        const palette = await import('../services/article-colors.service');
        assert.deepEqual(await palette.getArticleColors('owner'), { recent: [], custom: [] });
        await palette.recordArticleColor('owner', '#6395cf');
        await palette.recordArticleColor('owner', '#123456');
        await palette.recordArticleColor('owner', '#6395CF');
        assert.deepEqual(await palette.getArticleColors('owner'), { recent: ['#6395cf'], custom: ['#123456'] });
        assert.deepEqual(await palette.getArticleColors('admin'), { recent: [], custom: [] });
        await palette.recordArticleColor('admin', '#da7272');
        assert.deepEqual((await palette.getArticleColors('owner')).recent, ['#6395cf']);
        await Promise.all([palette.recordArticleColor('owner', '#112233'), palette.recordArticleColor('owner', '#445566')]);
        assert.equal((await palette.getArticleColors('owner')).custom.length, 3);
        await assert.rejects(palette.recordArticleColor('owner', 'javascript:x'), { status: 400 });
        const service = await import('../services/articles.service');
        const images = await import('../services/article-images.service');
        const make = (title: string, body = 'Hello') => ({ title, introduction: `${title} introduction`, document: markdownToDocument(body) });
        const translations: ArticleTranslations = { en: make('English'), fr: make('Français', 'Bonjour') };
        let draft = await service.saveDraft('owner', { translations, selectedTagIds: [] });
        const previewDraft = await service.saveDraft('owner', { translations: { en: make('Preview', '## Preview heading\n\n**Bold** paragraph\n\n- List item\n\nFourth block is hidden') } });
        const preview = await service.getDraftPreview('owner', previewDraft.id);
        assert.ok(preview.html.includes('<h2>Preview heading</h2>'));
        assert.ok(preview.html.includes('<strong>Bold</strong>'));
        assert.ok(preview.html.includes('<li>'));
        assert.ok(!preview.html.includes('Fourth block is hidden'));
        await assert.rejects(service.getDraftPreview('admin', previewDraft.id), { status: 403 });
        await db.execute("INSERT INTO users (discord_user_id, username, avatar, role) VALUES ('other-owner', 'other', '', 'owner')");
        await assert.rejects(service.getDraftPreview('other-owner', previewDraft.id), { status: 404 });
        await service.removeDraft('owner', previewDraft.id);
        const sharp = (await import('sharp')).default;
        const bytes = await sharp({ create: { width: 1500, height: 900, channels: 3, background: 'red' } }).png().toBuffer();
        const image = await images.uploadArticleImage('owner', bytes, undefined, draft.id);
        const unused = await images.uploadArticleImage('owner', bytes, undefined, draft.id);
        await assert.rejects(images.deleteArticleImage('reader', unused.id), { status: 403 });
        await assert.rejects(images.deleteArticleImage('admin', unused.id), { status: 403 });
        await images.deleteArticleImage('owner', unused.id);
        await assert.rejects(images.readArticleImage(unused.id, 'owner'), { status: 404 });

        await assert.rejects(images.readArticleImage(image.id), { status: 404 });
        await assert.rejects(images.readArticleImage(image.id, 'reader'), { status: 403 });
        assert.ok((await images.readArticleImage(image.id, 'owner')).length);
        assert.equal((await sharp(await images.readArticleImage(image.id, 'owner')).metadata()).width, 1500);
        translations.en!.document.content.content!.push({ type: 'image', attrs: { src: image.url, alt: 'red image' } });
        draft = await service.saveDraft('owner', { id: draft.id, translations });
        assert.equal(draft.translations?.fr?.title, 'Français');
        await assert.rejects(images.deleteArticleImage('owner', image.id), { status: 409 });
        const created = await service.createArticle('owner', { draftId: draft.id, translations, status: 'published' });
        assert.equal(created.uid, draft.uid);
        assert.equal((await service.listOwnerDrafts('owner')).length, 0);
        assert.ok((await images.readArticleImage(image.id)).length);
        await assert.rejects(images.deleteArticleImage('admin', image.id), { status: 409 });
        assert.equal((await images.listArticleImages('admin', created.id))[0].id, image.id);
        const french = await service.getPublicArticle(created.slug, 'fr');
        assert.equal(french.title, 'Français'); assert.equal(french.resolvedLocale, 'fr'); assert.ok(french.sanitizedHtml.includes('Bonjour')); assert.equal(french.translations, undefined);
        const fallback = await service.getPublicArticle(created.slug, 'de');
        assert.equal(fallback.resolvedLocale, 'en'); assert.equal(fallback.requestedLocale, 'de'); assert.equal(fallback.title, 'English');
        assert.equal((await service.listPublicArticles({ search: 'Français', locale: 'fr' })).length, 1);
        assert.equal((await service.listPublicArticles({ search: 'English', locale: 'fr' })).length, 0);
        assert.equal((await service.listPublicArticles({ search: 'English', locale: 'de' })).length, 1);
        await assert.rejects(service.createArticle('admin', { translations }), { status: 403 });
        await assert.rejects(service.updateArticle('reader', created.id, { translations }), { status: 403 });
        await assert.rejects(service.updateArticle('admin', created.id, { translations: { en: translations.en, fr: make('') } }), { status: 400 });
        assert.equal((await service.getPublicArticle(created.slug, 'fr')).title, 'Français');
        const renamed = await service.updateArticle('admin', created.id, { translations: { ...translations, en: { ...translations.en!, title: 'Renamed' } } });
        assert.equal(renamed.slug, created.slug);
        const incomplete = await service.createArticle('owner', { translations: { en: make(''), fr: make('') }, status: 'unpublished' });
        await assert.rejects(service.setArticlePublication('admin', incomplete.id, { published: true }), { status: 400 });
        await service.setArticlePublication('admin', created.id, { published: true, publishedAt: '2030-01-01' });
        await assert.rejects(service.getPublicArticle(created.slug), { status: 404 });
        await assert.rejects(images.readArticleImage(image.id), { status: 404 });
        await service.setArticlePublication('admin', created.id, { published: true });
        await service.archiveArticle('owner', created.id);
        await assert.rejects(service.getPublicArticle(created.slug), { status: 404 });
        await assert.rejects(images.readArticleImage(image.id), { status: 404 });
        // Foreign draft images cannot be attached and the entire article write rolls back.
        const otherDraft = await service.saveDraft('owner', { translations: { en: make('Other') } });
        await assert.rejects(service.saveDraft('owner', { id: otherDraft.id, translations }), { status: 400 });
        assert.equal((await service.listOwnerDrafts('owner')).find(d => d.id === otherDraft.id)!.translations!.en!.title, 'Other');
        const orphan = await images.uploadArticleImage('owner', bytes, undefined, otherDraft.id);
        await db.execute('UPDATE article_images SET created_at = DATE_SUB(NOW(), INTERVAL 2 DAY)');
        await images.cleanupArticleImages();
        assert.ok((await images.readArticleImage(image.id, 'admin')).length);
        await assert.rejects(images.readArticleImage(orphan.id, 'owner'), { status: 404 });
        // Shared library uploads can be reused by different writers and survive cleanup.
        const shared = await images.uploadArticleImage('admin', bytes, undefined, undefined, true);
        assert.ok((await images.listArticleImages('owner')).some(item => item.id === shared.id));
        await assert.rejects(images.listArticleImages('reader'), { status: 403 });
        await assert.rejects(images.uploadArticleImage('reader', bytes, undefined, undefined, true), { status: 403 });
        assert.ok((await images.readArticleImage(shared.id, 'owner')).length);
        await assert.rejects(images.readArticleImage(shared.id), { status: 404 });
        await assert.rejects(images.deleteArticleImage('owner', shared.id), { status: 403 });
        const sharedTranslations = { en: make('Shared image', `![shared](${shared.url})`) };
        const sharedDraft = await service.saveDraft('owner', { translations: sharedTranslations });
        const sharedArticle = await service.createArticle('owner', { draftId: sharedDraft.id, translations: sharedTranslations, status: 'published' });
        const sharedAgain = await service.createArticle('owner', { translations: { en: make('Shared again', `![again](${shared.url})`) }, status: 'published' });
        assert.ok((await images.readArticleImage(shared.id)).length);
        await assert.rejects(images.deleteArticleImage('admin', shared.id), { status: 409 });
        await service.updateArticle('admin', sharedArticle.id, { translations: { en: make('Removed once') } });
        assert.ok((await images.readArticleImage(shared.id)).length);
        await service.updateArticle('admin', sharedAgain.id, { translations: { en: make('Removed twice') } });
        await assert.rejects(images.readArticleImage(shared.id), { status: 404 });
        await db.execute('UPDATE article_images SET created_at = DATE_SUB(NOW(), INTERVAL 2 DAY) WHERE id = ?', [shared.id]);
        await images.cleanupArticleImages();
        assert.ok((await images.readArticleImage(shared.id, 'owner')).length);
        await images.deleteArticleImage('admin', shared.id);
        const legacyId = randomUUID();
        await db.execute("INSERT INTO articles (id, uid, slug, title, introduction, markdown_source, sanitized_html, excerpt, author_id) VALUES (?, 'legacy-test', 'legacy-test', 'Legacy', 'Intro', '# Original', '<h1>Original</h1>', 'Original', 'owner')", [legacyId]);
        const { migrateArticleDocuments } = await import('../core/articles/migration');
        await migrateArticleDocuments(); await migrateArticleDocuments();
        const migrated = await service.getAdminArticle('admin', legacyId);
        assert.equal(migrated.translations!.en!.title, 'Legacy');
        assert.equal(migrated.markdownSource, '# Original');
        assert.equal(migrated.slug, 'legacy-test');
    } finally {
        await db?.pool.end();
        await admin.query(`DROP DATABASE IF EXISTS \`${database}\``);
        await admin.end();
    }
});
