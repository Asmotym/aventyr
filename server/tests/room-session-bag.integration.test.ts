import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import type { BagAction, BagActionName, BagSnapshot } from '../core/types/bag.types';

test('Session bag MySQL: transactional counters, privacy, expiry and frozen history', { skip: process.env.BAG_INTEGRATION !== '1' }, async () => {
    const { config } = await import('dotenv'); config();
    const mysql = await import('mysql2/promise');
    const database = `rolz_bag_test_${randomUUID().replaceAll('-', '')}`;
    const admin = await mysql.createConnection({ host: '127.0.0.1', port: Number(process.env.MYSQL_PORT ?? 3306), user: 'root', password: process.env.MYSQL_ROOT_PASSWORD ?? 'root' });
    let db: typeof import('../core/database/client') | undefined;
    try {
        await admin.query(`CREATE DATABASE \`${database}\``);
        const url = new URL(`mysql://root@127.0.0.1:${process.env.MYSQL_PORT ?? 3306}/${database}`); url.password = process.env.MYSQL_ROOT_PASSWORD ?? 'root';
        process.env.DATABASE_URL = url.toString(); process.env.DATABASE_SSL = 'false';
        db = await import('../core/database/client');
        const { ensureDatabaseSetup } = await import('../core/database/schema');
        await ensureDatabaseSetup(); await ensureDatabaseSetup();
        for (const id of ['owner', 'alice', 'bob', 'outsider']) await db.execute("INSERT INTO users (discord_user_id, username, avatar) VALUES (?, ?, '')", [id, id]);
        const roomId = randomUUID();
        await db.execute("INSERT INTO rooms (id, name, invite_code, created_by) VALUES (?, 'Bag Test', 'bag-test', 'owner')", [roomId]);
        for (const id of ['owner', 'alice', 'bob']) await db.execute('INSERT INTO room_members (id, room_id, user_id, role) VALUES (?, ?, ?, ?)', [randomUUID(), roomId, id, id === 'owner' ? 'creator' : 'player']);
        const { handleBagAction } = await import('../services/rooms/room-bag.service');
        const run = (action: BagActionName, userId = 'alice', extra: Partial<BagAction['payload']> = {}) => handleBagAction({ action, payload: { roomId, userId, scope: 'team', ...extra } });
        const read = async (userId = 'alice', scope: 'team' | 'personal' = 'team'): Promise<BagSnapshot> => { const r = await run('bag', userId, { scope }); if (!('bag' in r) || !r.bag) throw new Error('Missing bag'); return r.bag; };
        const sessions = await import('../services/rooms/room-sessions.service');
        await run('setBagEnabled', 'owner', { enabled: true });
        await run('createBagItem', 'alice', { data: { name: 'Before session' } });
        assert.equal(await sessions.getActiveRoomSession(roomId), null);
        const session = await sessions.startRoomSession(roomId, 'owner');
        const originalActivity = session.lastActivityAt;
        await run('createBagItem', 'alice', { data: { name: 'Sword' } });
        let sword = (await read()).items.find(item => item.name === 'Sword')!;
        for (let i = 0; i < 2; i++) {
            await run('updateBagItem', 'alice', { id: sword.id, revision: sword.revision, data: { name: 'Sword' } });
            sword = (await read()).items.find(item => item.id === sword.id)!;
        }
        await assert.rejects(run('updateBagItem', 'alice', { id: sword.id, revision: 0, data: { name: 'Stale' } }), { status: 409 });
        await run('setBagItemFavorite', 'alice', { id: sword.id, revision: sword.revision, favorite: true });
        sword = (await read()).items.find(item => item.id === sword.id)!;
        await run('giveBagItem', 'alice', { id: sword.id, revision: sword.revision, targetUserId: 'bob' });
        const pending = (await read('bob')).incomingGifts!.find(g => g.item.id === sword.id)!;
        await run('rejectBagItem', 'bob', { id: sword.id, revision: pending.item.revision });
        sword = (await read()).items.find(item => item.id === sword.id)!;
        await run('deleteBagItem', 'alice', { id: sword.id, revision: sword.revision });
        await run('createBagItem', 'alice', { scope: 'personal', data: { name: 'Private' } });
        await run('createBagItem', 'bob', { scope: 'personal', data: { name: 'Other private' } });
        const personalGift = (await read('alice', 'personal')).items[0]!;
        await run('giveBagItem', 'alice', { scope: 'personal', id: personalGift.id, revision: personalGift.revision, targetUserId: 'bob' });
        const personalPending = (await read('bob', 'personal')).incomingGifts!.find(g => g.item.id === personalGift.id)!;
        await run('acceptBagItem', 'bob', { scope: 'personal', id: personalGift.id, revision: personalPending.item.revision, destinationSectionId: null });
        assert.deepEqual((await sessions.getRoomSessionRecap(roomId, session.id, 'bob')).recap.bag?.personal, { created: 1, edited: 0, deleted: 0, gifted: 0 });
        const alice = await sessions.getRoomSessionRecap(roomId, session.id, 'alice');
        assert.deepEqual(alice.recap.bag?.team, { created: 1, edited: 2, deleted: 1, gifted: 1 });
        assert.deepEqual(alice.recap.bag?.personal, { created: 1, edited: 0, deleted: 0, gifted: 1 });
        assert.equal(JSON.stringify(alice.recap.bag).includes('personalByOwner'), false);
        await assert.rejects(sessions.getRoomSessionRecap(roomId, session.id, 'outsider'), { status: 403 });
        const active = (await sessions.getActiveRoomSession(roomId))!;
        assert.equal(active.lastActivityAt, originalActivity);
        assert.equal(active.recap.bag?.personal, undefined);
        const closed = await sessions.closeRoomSession(roomId, 'owner');
        assert.equal(closed.recap.bag?.personal, undefined);
        await run('createBagItem', 'alice', { data: { name: 'After session' } });
        assert.deepEqual((await sessions.getRoomSessionRecap(roomId, session.id, 'alice')).recap.bag, alice.recap.bag);
        await run('setBagEnabled', 'owner', { enabled: false });
        assert.deepEqual((await sessions.getRoomSessionRecap(roomId, session.id, 'alice')).recap.bag, alice.recap.bag);
        await run('setBagEnabled', 'owner', { enabled: true });
        const second = await sessions.startRoomSession(roomId, 'owner');
        await db.execute('UPDATE room_sessions SET last_activity_at = DATE_SUB(NOW(), INTERVAL 8 DAY) WHERE id = ?', [second.id]);
        await run('createBagItem', 'alice', { data: { name: 'Expired' } });
        assert.equal((await sessions.getRoomSessionRecap(roomId, second.id, 'alice')).recap.bag?.team.created, 0);
        await sessions.closeRoomSession(roomId, 'owner');
        const legacy = await sessions.startRoomSession(roomId, 'owner');
        await db.execute("UPDATE room_sessions SET configuration_json = JSON_REMOVE(configuration_json, '$.bagTrackingVersion') WHERE id = ?", [legacy.id]);
        await run('createBagItem', 'alice', { data: { name: 'Legacy' } });
        assert.equal((await sessions.getRoomSessionRecap(roomId, legacy.id, 'alice')).recap.bag, undefined);
        await sessions.closeRoomSession(roomId, 'owner');
        const race = await sessions.startRoomSession(roomId, 'owner');
        await Promise.all([run('createBagItem', 'alice', { data: { name: 'Race' } }), sessions.closeRoomSession(roomId, 'owner')]);
        const [rows] = await db.pool.query('SELECT COUNT(*) AS count FROM room_session_bag_events WHERE session_id = ?', [race.id]);
        assert.equal((await sessions.getRoomSessionRecap(roomId, race.id, 'alice')).recap.bag?.team.created, Number((rows as any[])[0].count));
    } finally { if (db) await db.pool.end(); await admin.query(`DROP DATABASE IF EXISTS \`${database}\``); await admin.end(); }
});
